#!/usr/bin/env python3
from __future__ import annotations
"""
Generate Apptainer/Singularity instance launch script + container_config.json.

Parallel to generate_compose.py but targets Apptainer for HPC (Slurm) clusters.
Containers run as long-lived instances with host networking on unique ports.

Usage:
  # Basic (8 containers with GPU)
  python executors/generate_apptainer.py \
    --num-containers 8 \
    --sif-image executors/images/kaggle_executor.sif \
    --mountable-volumes ../data/data \
    --mountable-volume-saveto ../submissions \
    --gpu-ids 0,1,2,3,4,5,6,7

  # Without GPU (CPU only)
  python executors/generate_apptainer.py \
    --num-containers 4 \
    --sif-image executors/images/kaggle_executor.sif \
    --mountable-volumes ../data/data \
    --mountable-volume-saveto ../submissions

  # Build the .sif image first:
  cd executors/container_images/kaggle_image
  apptainer build kaggle_executor.sif kaggle_executor.def
"""

import argparse
import json
import os
import stat
from pathlib import Path


def generate_instance_name(container_id: int) -> str:
    return f"executor-{container_id:03d}"


def generate_launch_script(
    num_containers: int,
    sif_image: str,
    start_port: int = 60000,
    mountable_volumes: str | None = None,
    mountable_volume_saveto: str | None = None,
    gpu_ids: list[int] | None = None,
    extra_env: dict | None = None,
    execution_timeout: int = 3600,
    output_file: str = "launch_instances.sh",
    tmp_root: str | None = None,
) -> None:
    """Generate a shell script that launches N Apptainer instances.

    If ``tmp_root`` is given, each container gets a disk-backed per-container
    ``/tmp`` bound from ``tmp_root/container_XXX`` instead of the default 16 MB
    in-memory tmpfs. The tiny tmpfs (with --containall blocking the host /tmp)
    is what starves IPython's history/temp DB and kills the kernel with
    "No usable temporary directory found".
    """

    lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated by generate_apptainer.py",
        "# Launches Apptainer executor instances with unique ports",
        "",
        "set -euo pipefail",
        "",
        f'SIF_IMAGE="{sif_image}"',
        "",
        "# Verify image exists",
        'if [ ! -f "$SIF_IMAGE" ]; then',
        '    echo "ERROR: SIF image not found: $SIF_IMAGE"',
        '    echo "Build it with: apptainer build kaggle_executor.sif kaggle_executor.def"',
        "    exit 1",
        "fi",
        "",
    ]

    # Create submission directories
    if mountable_volume_saveto:
        lines.append(f'SUBMISSION_BASE="{mountable_volume_saveto}"')
        lines.append('mkdir -p "$SUBMISSION_BASE"')
        for i in range(num_containers):
            lines.append(f'mkdir -p "$SUBMISSION_BASE/container_{i:03d}"')
        lines.append("")

    if tmp_root:
        lines.append(f'TMP_BASE="{tmp_root}"')
        lines.append('mkdir -p "$TMP_BASE"')
        lines.append("")

    lines.append(f'echo "Starting {num_containers} instances..."')
    lines.append("")

    # Launch each instance
    for i in range(num_containers):
        port = start_port + i
        instance_name = generate_instance_name(i)
        gpu_id = gpu_ids[i] if gpu_ids else None

        lines.append(f"# --- Container {i} ({instance_name}) on port {port} ---")
        if tmp_root:
            lines.append(f'mkdir -p "$TMP_BASE/container_{i:03d}"')

        # Build bind mounts
        binds = []
        if mountable_volumes:
            binds.append(f"{mountable_volumes}:/data:ro")
        if mountable_volume_saveto:
            binds.append(f"{mountable_volume_saveto}/container_{i:03d}:/submission")
        if tmp_root:
            # Disk-backed per-container /tmp so IPython's history/temp DB has room.
            binds.append(f'"$TMP_BASE/container_{i:03d}":/tmp')

        # Build environment variables
        env_vars = {
            "PORT": str(port),
            "CONTAINER_ID": str(i),
            "HOST_PORT": str(port),
            "PYTHONUNBUFFERED": "1",
            "PYTHONDONTWRITEBYTECODE": "1",
            "EXECUTION_TIMEOUT": str(execution_timeout),
        }
        if mountable_volumes:
            env_vars["WORKSPACE_FOLDER"] = "/data"
        if mountable_volume_saveto:
            env_vars["SUBMISSION_DIR"] = "/submission"
        if extra_env:
            env_vars.update(extra_env)

        # Build the apptainer instance start command
        cmd_parts = ["apptainer instance start"]

        # GPU passthrough
        if gpu_id is not None:
            cmd_parts.append("--nv")
            env_vars["CUDA_VISIBLE_DEVICES"] = str(gpu_id)

        # Writable tmpfs overlay (Apptainer images are read-only by default)
        cmd_parts.append("--writable-tmpfs")

        # Filesystem isolation: prevent container from accessing $HOME, /tmp, CWD
        # from the host. Only explicit --bind paths are visible inside.
        cmd_parts.append("--containall")
        cmd_parts.append("--no-home")

        # Bind mounts
        for bind in binds:
            cmd_parts.append(f"--bind {bind}")

        # Environment variables
        for key, value in env_vars.items():
            cmd_parts.append(f"--env {key}={value}")

        # Network: use host network (instances share host's network stack)
        cmd_parts.append("--net --network none")
        # Note: --network none + host port binding isn't needed because
        # Apptainer instances share the host network by default (no isolation).
        # We remove --net --network none and just let it use host networking.

        # Actually, Apptainer uses host networking by default (no network namespace).
        # Remove the --net flag. The process inside binds to 0.0.0.0:PORT directly.
        cmd_parts = [p for p in cmd_parts if p not in ("--net --network none",)]

        # Image and instance name
        cmd_parts.append(f'"$SIF_IMAGE"')
        cmd_parts.append(instance_name)

        # Join with line continuations for readability
        cmd = " \\\n    ".join(cmd_parts)
        lines.append(cmd)
        lines.append(f'echo "  Started {instance_name} (port {port})"')
        lines.append("")

    # Summary
    lines.append(f'echo ""')
    lines.append(f'echo "All {num_containers} instances launched."')
    lines.append(f'echo "Ports: {start_port}-{start_port + num_containers - 1}"')
    lines.append(f'echo ""')
    lines.append(f'echo "Check status:  apptainer instance list"')
    lines.append(f'echo "View logs:     apptainer exec instance://<name> cat /proc/1/fd/1"')
    lines.append(f'echo "Stop all:      apptainer instance stop --all"')
    lines.append("")

    with open(output_file, "w") as f:
        f.write("\n".join(lines))

    # Make executable
    os.chmod(output_file, os.stat(output_file).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"Generated {output_file}")


def generate_stop_script(num_containers: int, output_file: str = "stop_instances.sh") -> None:
    """Generate a script to stop all instances."""
    lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated by generate_apptainer.py",
        "# Stops all executor Apptainer instances",
        "",
        "set -euo pipefail",
        "",
    ]

    for i in range(num_containers):
        instance_name = generate_instance_name(i)
        lines.append(f'apptainer instance stop {instance_name} 2>/dev/null && echo "Stopped {instance_name}" || true')

    lines.append("")
    lines.append('echo "All instances stopped."')

    with open(output_file, "w") as f:
        f.write("\n".join(lines))

    os.chmod(output_file, os.stat(output_file).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"Generated {output_file}")


def generate_container_config(
    num_containers: int,
    start_port: int = 60000,
    hostname: str = "localhost",
    output_file: str = "container_config.json",
) -> None:
    """Generate container_config.json for the manager service."""
    config = {}
    for i in range(num_containers):
        port = start_port + i
        config[str(i)] = {
            "url": f"http://{hostname}:{port}",
            "type": "kaggle_executor",
        }

    with open(output_file, "w") as f:
        json.dump(config, f, indent=2)

    print(f"Generated {output_file}")
    print(f"  {num_containers} containers: ports {start_port}-{start_port + num_containers - 1}")
    print(f"  Hostname: {hostname}")


def generate_slurm_job(
    num_containers: int,
    sif_image: str,
    start_port: int = 60000,
    mountable_volumes: str | None = None,
    mountable_volume_saveto: str | None = None,
    num_gpus: int = 0,
    partition: str = "gpu",
    time_limit: str = "24:00:00",
    output_file: str = "slurm_job.sh",
) -> None:
    """Generate a Slurm job script that launches instances + manager + collection."""
    lines = [
        "#!/usr/bin/env bash",
        f"#SBATCH --job-name=dsgym-executors",
        f"#SBATCH --partition={partition}",
        f"#SBATCH --time={time_limit}",
        f"#SBATCH --nodes=1",
        f"#SBATCH --ntasks=1",
        f"#SBATCH --cpus-per-task={num_containers * 8}",
        f"#SBATCH --mem={num_containers * 24}G",
    ]

    if num_gpus > 0:
        lines.append(f"#SBATCH --gres=gpu:{num_gpus}")

    lines.extend([
        "#SBATCH --output=slurm-%j.out",
        "#SBATCH --error=slurm-%j.err",
        "",
        "set -euo pipefail",
        "",
        "echo \"Job started on $(hostname) at $(date)\"",
        "",
        "# Launch executor instances",
        "./launch_instances.sh",
        "",
        "# Wait for instances to be ready",
        "echo \"Waiting for instances to start...\"",
        "sleep 10",
        "",
        "# Health check",
        f"for port in $(seq {start_port} {start_port + num_containers - 1}); do",
        "    until curl -s http://localhost:$port/health > /dev/null 2>&1; do",
        "        sleep 2",
        "    done",
        "    echo \"  Port $port ready\"",
        "done",
        "",
        "echo \"All executors healthy. Starting manager...\"",
        "",
        "# Launch manager (run in background)",
        "# The manager reads container_config.json and proxies requests",
        "cd executors/manager && python main.py &",
        "MANAGER_PID=$!",
        "sleep 5",
        "",
        "echo \"Manager started (PID=$MANAGER_PID). Ready for collection.\"",
        "",
        "# Run trajectory collection",
        "# Uncomment and customize:",
        "# python scripts/adapra/collect_trajectories.py \\",
        "#     --dataset dspredict-easy \\",
        "#     --output-dir outputs/adapra/bon/trajectories/dspredict-easy-bon5 \\",
        "#     --manager-url http://localhost:5001 \\",
        "#     --workers 4",
        "",
        "# Wait for collection to finish, then cleanup",
        "wait",
        "",
        "# Cleanup",
        "./stop_instances.sh",
        "kill $MANAGER_PID 2>/dev/null || true",
        "",
        "echo \"Job finished at $(date)\"",
    ])

    with open(output_file, "w") as f:
        f.write("\n".join(lines))

    os.chmod(output_file, os.stat(output_file).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"Generated {output_file}")


def parse_env_vars(env_string: str) -> dict:
    """Parse environment variables from KEY=VALUE,KEY2=VALUE2 format."""
    env_dict = {}
    if env_string:
        for pair in env_string.split(","):
            if "=" in pair:
                key, value = pair.split("=", 1)
                env_dict[key.strip()] = value.strip()
    return env_dict


def parse_gpu_ids(gpu_string: str) -> list[int]:
    """Parse GPU IDs from comma-separated string."""
    return [int(g.strip()) for g in gpu_string.split(",")]


def main():
    parser = argparse.ArgumentParser(
        description="Generate Apptainer instance launch scripts + container_config.json"
    )
    parser.add_argument("--num-containers", "-n", type=int, default=8,
                        help="Number of executor instances (default: 8)")
    parser.add_argument("--sif-image", required=True,
                        help="Path to the .sif image file")
    parser.add_argument("--start-port", "-p", type=int, default=60000,
                        help="Starting port number (default: 60000)")
    parser.add_argument("--mountable-volumes", "-m",
                        help="Host directory to mount as /data (read-only)")
    parser.add_argument("--mountable-volume-saveto", "-s",
                        help="Host directory for per-container /submission mounts")
    parser.add_argument("--gpu-ids", "-g",
                        help="GPU IDs to assign, comma-separated (e.g. 0,1,2,3)")
    parser.add_argument("--env", "-e",
                        help="Extra env vars: KEY=VALUE,KEY2=VALUE2")
    parser.add_argument("--execution-timeout", type=int, default=3600,
                        help="Per-cell execution timeout in seconds (default: 3600)")
    parser.add_argument("--tmp-root",
                        help="Host dir (e.g. on scratch) for disk-backed per-container "
                             "/tmp binds. Prevents the 16MB tmpfs from starving IPython's "
                             "history/temp DB (which kills the kernel).")
    parser.add_argument("--hostname", default="localhost",
                        help="Hostname for container_config.json URLs (default: localhost)")
    parser.add_argument("--output-dir", "-o", default=".",
                        help="Directory to write generated files (default: .)")
    parser.add_argument("--slurm", action="store_true",
                        help="Also generate a Slurm job script")
    parser.add_argument("--slurm-partition", default="gpu",
                        help="Slurm partition name (default: gpu)")
    parser.add_argument("--slurm-time", default="24:00:00",
                        help="Slurm time limit (default: 24:00:00)")
    parser.add_argument("--config-file", "-c", default="container_config.json",
                        help="Container config filename (default: container_config.json)")

    args = parser.parse_args()

    # Parse optional args
    gpu_ids = parse_gpu_ids(args.gpu_ids) if args.gpu_ids else None
    extra_env = parse_env_vars(args.env) if args.env else None

    # Validate GPU count matches container count
    if gpu_ids and len(gpu_ids) != args.num_containers:
        parser.error(
            f"Number of GPU IDs ({len(gpu_ids)}) must match "
            f"--num-containers ({args.num_containers})"
        )

    # Resolve output directory
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"Generating Apptainer configuration:")
    print(f"  Containers: {args.num_containers}")
    print(f"  SIF image: {args.sif_image}")
    print(f"  Ports: {args.start_port}-{args.start_port + args.num_containers - 1}")
    if args.mountable_volumes:
        print(f"  Data mount: {args.mountable_volumes} -> /data (ro)")
    if args.mountable_volume_saveto:
        print(f"  Submission mount: {args.mountable_volume_saveto}/container_XXX -> /submission")
    if gpu_ids:
        print(f"  GPUs: {gpu_ids}")
    print()

    # Generate launch script
    generate_launch_script(
        num_containers=args.num_containers,
        sif_image=args.sif_image,
        start_port=args.start_port,
        mountable_volumes=args.mountable_volumes,
        mountable_volume_saveto=args.mountable_volume_saveto,
        gpu_ids=gpu_ids,
        extra_env=extra_env,
        execution_timeout=args.execution_timeout,
        output_file=str(out_dir / "launch_instances.sh"),
        tmp_root=args.tmp_root,
    )

    # Generate stop script
    generate_stop_script(
        num_containers=args.num_containers,
        output_file=str(out_dir / "stop_instances.sh"),
    )

    # Generate container_config.json
    generate_container_config(
        num_containers=args.num_containers,
        start_port=args.start_port,
        hostname=args.hostname,
        output_file=str(out_dir / args.config_file),
    )

    # Optionally generate Slurm job script
    if args.slurm:
        num_gpus = len(gpu_ids) if gpu_ids else 0
        generate_slurm_job(
            num_containers=args.num_containers,
            sif_image=args.sif_image,
            start_port=args.start_port,
            mountable_volumes=args.mountable_volumes,
            mountable_volume_saveto=args.mountable_volume_saveto,
            num_gpus=num_gpus,
            partition=args.slurm_partition,
            time_limit=args.slurm_time,
            output_file=str(out_dir / "slurm_job.sh"),
        )

    print()
    print("Next steps:")
    print("  1. Build the SIF image:")
    print("     cd executors/container_images/kaggle_image")
    print("     apptainer build kaggle_executor.sif kaggle_executor.def")
    print("  2. Launch instances:")
    print(f"     cd {out_dir} && ./launch_instances.sh")
    print("  3. Start manager (point at generated config):")
    print(f"     PORT=5001 CONTAINER_CONFIG_PATH={out_dir / args.config_file} python executors/manager/main.py")
    print("  4. Run collection:")
    print("     python scripts/adapra/collect_trajectories.py --manager-url http://localhost:5001 ...")


if __name__ == "__main__":
    main()
