def prm_instruction(rubric: RubricDef, style: str = "labels") -> str:
    """Return the scoring instruction for a rubric in the requested STYLE.

    - style="labels" (default): the canonical 4-label
      (agent_failure/success/not_applicable/insufficient_evidence) instruction.
    - style="p_success": the alternate instruction phrased directly on the
      continuous p_agent_success 0-1 scale, falling back to the 4-label text when
      p_success_instruction is not populated for this rubric.

    Additive + reversible: callers pass style="p_success" to opt in; the default
    preserves existing behavior exactly.
    """
    if style == "p_success" and rubric.p_success_instruction:
        return rubric.p_success_instruction
    return rubric.natural_language_instruction or rubric.description


def get_rubric(rubric_id: str) -> RubricDef:
    if rubric_id not in RUBRIC_REGISTRY:
        raise KeyError(f"Unknown rubric: {rubric_id!r}. Available: {list(RUBRIC_REGISTRY)}")
    return RUBRIC_REGISTRY[rubric_id]


def list_rubrics(category: Optional[str] = None, dataset: Optional[str] = None) -> list[RubricDef]:
    rubrics = list(RUBRIC_REGISTRY.values())
    if category:
        rubrics = [r for r in rubrics if r.category == category]
    if dataset:
        rubrics = [r for r in rubrics if not r.applicable_datasets or dataset in r.applicable_datasets]
    return rubrics
