# Symbolic rubric-set names → shipped JSON. A launch command / config may pass a
# short name (e.g. "discovered") instead of a filesystem path so the SAME config
# resolves correctly on the host AND inside an apptainer instance where the repo
# lives at a different absolute path (the JSON is package data, resolved from
# this module's __file__). Any value that isn't a known name is treated as a path.
_RUBRIC_SET_ALIASES = {
    "discovered": DSPREDICT_DISCOVERED_JSON,
    "dspredict_discovered": DSPREDICT_DISCOVERED_JSON,
    "discovered_xattempt": DSPREDICT_DISCOVERED_XATTEMPT_JSON,
    "dspredict_discovered_xattempt": DSPREDICT_DISCOVERED_XATTEMPT_JSON,
    "union_stacked": DSPREDICT_UNION_STACKED_JSON,
    "dspredict_union_stacked": DSPREDICT_UNION_STACKED_JSON,
}


def _resolve_rubric_set_path(rubric_set: str) -> Path:
    """Map a rubric_set spec (symbolic name OR path) to a concrete JSON path."""
    return Path(_RUBRIC_SET_ALIASES.get(rubric_set, rubric_set))


def resolve_rubric_set(dataset: Optional[str] = None,
                       rubric_set: Optional[str] = None,
                       skip: Optional[set[str]] = None,
                       include_ids: Optional[set[str]] = None) -> list[RubricDef]:
    """The single place a PRM decides WHICH rubrics to score.

    - `rubric_set`: path to a rubric-set JSON (e.g. the discovered unified set).
      When given, the rubrics come ENTIRELY from that file — the registry is NOT
      consulted — so a launch command fixes the set explicitly and never doubles
      the hand-authored registry rubrics. The set is also registered (harmless;
      lets RUBRIC_REGISTRY.get(id) resolve display names for feedback). When
      omitted, falls back to list_rubrics(dataset=…) (the hand-authored set).
    - `skip`: rubric_ids to drop (SKIP_RUBRICS ∪ per-run excludes).
    - `include_ids`: if given, keep only these rubric_ids (post-skip).
    Returns the ordered RubricDef list to score.
    """
    if rubric_set:
        rubrics = load_rubrics_from_json(_resolve_rubric_set_path(rubric_set), register=True)
    else:
        rubrics = list_rubrics(dataset=dataset)
    if skip:
        rubrics = [r for r in rubrics if r.rubric_id not in skip]
    if include_ids:
        rubrics = [r for r in rubrics if r.rubric_id in include_ids]
    return rubrics


