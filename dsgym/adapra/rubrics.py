"""
AdaPRA rubric registry.

25 rubrics across 5 categories (A–E) targeting competitive predictive modeling quality.
13 rubrics across 4 categories (F–I) targeting analytical/QA dataset quality.

Framing convention (uniform across all rubrics):
  violated             = the failure described by the rubric IS present in the trajectory
  satisfied            = the failure is NOT present; the agent handled this correctly
  insufficient_evidence = the trajectory lacks enough information to evaluate this specific rubric

Each rubric instruction explicitly defines what each label means for that rubric.

applicable_datasets: tuple of dataset names this rubric applies to.
  - () (empty) means applicable to ALL datasets.
  - ("dspredict-easy", "dspredict-hard") means DSPredict tasks only.
  - ("discoverybench", "dabstep", ...) means analytical tasks only.
"""

import json
from dataclasses import dataclass, field, replace, fields
from pathlib import Path
from typing import Optional


@dataclass(frozen=True)
class RubricDef:
    rubric_id: str
    category: str        # A–I
    description: str
    natural_language_instruction: str = ""
    annotation_hint: str = ""
    applicable_datasets: tuple[str, ...] = ()
    # Neutral TOPIC label for display in feedback (e.g. "Cross-Validation
    # Consistency"), decoupled from the failure-oriented rubric_id. rubric_id
    # stays the stable key (SKIP_RUBRICS, prm_call JSONs, history); display_name
    # is only for rendering, so a PASSED failure-rubric doesn't read as "keep
    # doing Inconsistent Cross Validation". Falls back to the prettified id.
    display_name: str = ""
    # Neutral, good-practice-framed description for display (e.g. "Uses one
    # consistent CV scheme so model scores are comparable"), so a rubric shown
    # under "Strengths" doesn't carry a failure-worded Definition. `description`
    # stays failure-framed (it defines what a violation is). Falls back to it.
    display_description: str = ""
    # ALTERNATE scoring instruction phrased directly on the continuous
    # p_agent_success scale (0.0-1.0) instead of the 4-label scheme. Additive +
    # reversible: consumers opt in via prm_instruction(rubric, style="p_success");
    # when empty they fall back to natural_language_instruction, so nothing
    # changes until a caller selects this style AND the field is populated.
    p_success_instruction: str = ""
    # ADVISORY evidence-source hint from offline discovery: "artifact" (checkable
    # from the workspace W alone) or "trajectory" (checkable only from the
    # process). This is a RECOMMENDATION, not a constraint — the supervisor may
    # apply the rubric to whichever of tau / W it finds decisive. Rendered as a
    # suggestion in the PRM prompt; empty for the hand-authored rubrics.
    grounding: str = ""


_DSPREDICT = ("dspredict-easy", "dspredict-hard")
_ANALYTICAL = ("discoverybench", "dabstep", "qrdata", "daeval")

RUBRIC_REGISTRY: dict[str, RubricDef] = {}


def _reg(r: RubricDef) -> RubricDef:
    RUBRIC_REGISTRY[r.rubric_id] = r
    return r


# ── JSON-driven rubric sets ─────────────────────────────────────────────────
# The offline-discovered "unified PRM" seed set lives as raw JSON under
# rubric_sets/ and is built into RubricDef instances at import time by the loader
# below. This keeps the discovered set as data (regenerated by the discovery
# pipeline) rather than hand-transcribed Python, and lets a script round-trip it.
_RUBRIC_SET_DIR = Path(__file__).parent / "rubric_sets"

# JSON keys that map onto a differently-named RubricDef field.
_JSON_FIELD_ALIASES = {"suggested_actions_hint": "annotation_hint"}
_RUBRICDEF_FIELDS = {f.name for f in fields(RubricDef)}


def rubricdef_from_dict(d: dict) -> RubricDef:
    """Build a RubricDef from a raw JSON rubric dict. Provenance-only keys
    (supporting_behavior_count, example_evidence, vs_old_hand_set, keep, …) are
    ignored; `suggested_actions_hint` maps to `annotation_hint`; a list
    `applicable_datasets` is coerced to a tuple."""
    kw = {}
    for k, v in d.items():
        k = _JSON_FIELD_ALIASES.get(k, k)
        if k not in _RUBRICDEF_FIELDS:
            continue
        if k == "applicable_datasets" and isinstance(v, (list, tuple)):
            v = tuple(v)
        kw[k] = v
    return RubricDef(**kw)


def load_rubrics_from_json(path, register: bool = True,
                           keep_only: bool = True) -> list[RubricDef]:
    """Load a rubric set from a JSON file (either a bare list of rubric dicts or
    an object with a "rubrics" key) into RubricDef instances. When `keep_only`,
    entries flagged "keep": False are skipped (the author pass that drops, e.g.,
    the workspace/data-mount artifact). When `register`, each is added to
    RUBRIC_REGISTRY (later loads override earlier same-id entries)."""
    data = json.loads(Path(path).read_text())
    raw = data["rubrics"] if isinstance(data, dict) else data
    out: list[RubricDef] = []
    for d in raw:
        if keep_only and d.get("keep") is False:
            continue
        r = rubricdef_from_dict(d)
        if register:
            _reg(r)
        out.append(r)
    return out


